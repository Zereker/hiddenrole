// Package avalon 在 hiddenrole 内核上实现《抵抗组织：阿瓦隆》。
//
// 它是一个**示例**：一套完整可玩的规则，全部经内核的公开选项装配，没有后门。
// 同时它也是内核变更与静默回归之间的两道拦网之一，见 ../README.md。
//
// # 为什么这一套值得留着
//
// 狼人杀的形状就是内核长大时的形状，所以它证明不了内核是通用的。这套规则
// 和它几乎处处不同：
//
//	一个人都不出局      出局是内核唯一的生死原语，而这套规则根本不用它
//	不属于任何人的状态   第几轮任务、连续否决数、轮到谁带队——「整局、无主」那一格
//	运行时点名          队伍在提名阶段选出，在任务阶段行动
//	按结果分叉          通过去任务、否决回提名；静态相位图表达不了这句话
//	回合不等于绕一圈     一轮任务可能提名五次，回合数与循环不是同一件事
//
// 上面每一条，都是内核不得不放弃某个假设的地方——而只看狼人杀，那些假设
// 一个都不会被质疑。
//
// # 阅读顺序
//
//	vocab.go       词汇表：四个阶段、八个角色、六个技能
//	board.go       相位图
//	rules.go       装配：每一个扩展点，没有后门
//	resolver.go    每个阶段结束时意味着什么
//	boundary.go    谁有权知道什么（梅林、派西维尔、莫德雷德、奥伯伦）
//	victory.go     三次任务成功，然后是刺杀
//	SCARS.md       这套规则撞上内核形状的地方
